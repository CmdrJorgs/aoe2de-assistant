from enum import IntEnum
from typing import Dict, Any, Tuple, Optional


class Age(IntEnum):
    DARK = 1
    FEUDAL = 2
    CASTLE = 3
    IMPERIAL = 4

    @classmethod
    def from_name(cls, name: str) -> "Age":
        name_lower = name.lower()
        if "dark" in name_lower:
            return cls.DARK
        elif "feudal" in name_lower:
            return cls.FEUDAL
        elif "castle" in name_lower:
            return cls.CASTLE
        elif "imperial" in name_lower or "imp" in name_lower:
            return cls.IMPERIAL
        return cls.DARK

    @property
    def display_name(self) -> str:
        names = {
            Age.DARK: "Dark Age",
            Age.FEUDAL: "Feudal Age",
            Age.CASTLE: "Castle Age",
            Age.IMPERIAL: "Imperial Age",
        }
        return names.get(self, "Unknown Age")


