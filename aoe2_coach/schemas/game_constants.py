def get_canonical_object_name(object_id: int, fallback: str = "unknown") -> str:
    """Resolve raw numeric object ID to canonical string name."""
    return OBJECT_ID_TO_CANONICAL.get(object_id, f"{fallback}_{object_id}")


def get_canonical_tech_name(tech_id: int, fallback: str = "unknown_tech") -> str:
    """Resolve raw numeric technology ID to canonical string name."""
    return TECH_ID_TO_CANONICAL.get(tech_id, f"{fallback}_{tech_id}")


def get_civ_name(civ_id: int) -> str:
    """Resolve raw civ ID to standard name."""
    return CIVILIZATIONS.get(civ_id, f"Unknown Civ ({civ_id})")
